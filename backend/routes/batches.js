const express = require('express');
const router = express.Router();
const authenticate = require('../middleware/auth');
const { requireRole } = require('../middleware/role');
const Batch = require('../models/Batch');
const BatchChange = require('../models/BatchChange');
const Notification = require('../models/Notification');

// @route   POST /api/batches
// @desc    Create a new batch
// @access  Private (Farmer only)
router.post('/', authenticate, requireRole('farmer'), async (req, res) => {
  try {
    const {
      herbName,
      harvestDate,
      quantityKg,
      farmingConditions,
      moistureLevel,
      pricePerKg,
      purityReportUrl,
      images
    } = req.body;

    // Validation
    if (!herbName || !harvestDate || !quantityKg) {
      return res.status(400).json({
        success: false,
        message: 'Please provide herb name, harvest date, and quantity'
      });
    }

    // Create batch
    const batch = new Batch({
      batchNumber: '', // Will be auto-generated by pre-save hook
      farmerId: req.user.id,
      herbName,
      harvestDate: new Date(harvestDate),
      quantityKg: parseFloat(quantityKg),
      farmingConditions,
      moistureLevel: moistureLevel ? parseFloat(moistureLevel) : undefined,
      pricePerKg: pricePerKg ? parseFloat(pricePerKg) : undefined,
      purityReportUrl,
      images: images || [],
      status: 'pending_approval'
    });

    await batch.save();

    // Create notification for admin
    await Notification.create({
      userId: req.user.id, // This will be replaced by admin notification logic
      title: 'New Batch Created',
      message: `New batch ${batch.batchNumber} (${herbName}) is pending approval`,
      type: 'batch_created',
      relatedId: batch._id,
      relatedModel: 'Batch'
    });

    res.status(201).json({
      success: true,
      data: batch
    });
  } catch (error) {
    console.error('Create batch error:', error);
    res.status(500).json({
      success: false,
      message: 'Error creating batch',
      error: error.message
    });
  }
});

// @route   GET /api/batches
// @desc    Get all batches (with filters)
// @access  Private
router.get('/', authenticate, async (req, res) => {
  try {
    const { status, herbName, farmerId, page = 1, limit = 20, search } = req.query;
    
    const query = {};

    // Apply filters
    if (status) {
      query.status = status;
    }

    if (herbName) {
      query.herbName = { $regex: herbName, $options: 'i' };
    }

    if (farmerId) {
      query.farmerId = farmerId;
    }

    if (search) {
      query.$or = [
        { herbName: { $regex: search, $options: 'i' } },
        { batchNumber: { $regex: search, $options: 'i' } }
      ];
    }

    // Different query based on user role
    if (req.user.role === 'farmer') {
      query.farmerId = req.user.id;
    } else if (req.user.role === 'company') {
      // Companies can see batches in various statuses
      query.status = { $in: ['pending_approval', 'approved', 'in_process', 'quality_check', 'packaging', 'ready_for_sale', 'shipped', 'unavailable'] };
    }

    const skip = (parseInt(page) - 1) * parseInt(limit);

    const batches = await Batch.find(query)
      .populate('farmerId', 'fullName phone')
      .sort({ createdAt: -1 })
      .skip(skip)
      .limit(parseInt(limit));

    const total = await Batch.countDocuments(query);

    res.json({
      success: true,
      data: batches,
      pagination: {
        page: parseInt(page),
        limit: parseInt(limit),
        total,
        pages: Math.ceil(total / parseInt(limit))
      }
    });
  } catch (error) {
    console.error('Get batches error:', error);
    res.status(500).json({
      success: false,
      message: 'Error fetching batches',
      error: error.message
    });
  }
});

