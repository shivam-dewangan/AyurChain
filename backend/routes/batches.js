// @route   PUT /api/batches/:id
// @desc    Update batch
// @access  Private (Farmer only, owner of batch)
router.put('/:id', authenticate, requireRole('farmer'), async (req, res) => {
  try {
    const batch = await Batch.findById(req.params.id);

    if (!batch) {
      return res.status(404).json({
        success: false,
        message: 'Batch not found'
      });
    }

    // Check ownership
    if (batch.farmerId.toString() !== req.user.id) {
      return res.status(403).json({
        success: false,
        message: 'Not authorized to update this batch'
      });
    }

    // Only allow updates if batch is pending_approval
    if (batch.status !== 'pending_approval') {
      return res.status(400).json({
        success: false,
        message: 'Cannot update batch after approval process has started'
      });
    }

    const allowedUpdates = [
      'herbName', 'harvestDate', 'quantityKg', 'farmingConditions',
      'moistureLevel', 'pricePerKg', 'purityReportUrl', 'images'
    ];

    const updates = {};
    allowedUpdates.forEach(field => {
      if (req.body[field] !== undefined) {
        updates[field] = req.body[field];
      }
    });

    Object.assign(batch, updates);
    await batch.save();

    res.json({
      success: true,
      data: batch
    });
  } catch (error) {
    console.error('Update batch error:', error);
    res.status(500).json({
      success: false,
      message: 'Error updating batch',
      error: error.message
    });
  }
});

// @route   PATCH /api/batches/:id/status
// @desc    Update batch status
// @access  Private (Admin, Farmer for specific transitions)
router.patch('/:id/status', authenticate, async (req, res) => {
  try {
    const { status } = req.body;

    if (!status) {
      return res.status(400).json({
        success: false,
        message: 'Status is required'
      });
    }

    const batch = await Batch.findById(req.params.id);

    if (!batch) {
      return res.status(404).json({
        success: false,
        message: 'Batch not found'
      });
    }

    const oldStatus = batch.status;

    // Record status change
    await BatchChange.create({
      batchId: batch._id,
      fieldName: 'status',
      oldValue: oldStatus,
      newValue: status,
      changedBy: req.user.id
    });

    batch.status = status;
    
    // Handle sold/unavailable status
    if (status === 'sold' || status === 'unavailable') {
      batch.availableQuantityKg = 0;
    }

    await batch.save();

    // Notify farmer of status change
    await Notification.create({
      userId: batch.farmerId,
      title: 'Batch Status Updated',
      message: `Your batch ${batch.batchNumber} status changed to ${status}`,
      type: 'batch_status_changed',
      relatedId: batch._id,
      relatedModel: 'Batch'
    });

    res.json({
      success: true,
      data: batch
    });
  } catch (error) {
    console.error('Update status error:', error);
    res.status(500).json({
      success: false,
      message: 'Error updating status',
      error: error.message
    });
  }
});

